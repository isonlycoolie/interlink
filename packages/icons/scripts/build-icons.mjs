// Generates one module per glyph, a barrel, the metadata index and an SVG sprite from src/source.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src/source/core');
const gen = path.join(root, 'src/generated/core');
const dist = path.join(root, 'dist');
fs.rmSync(path.join(root, 'src/generated'), { recursive: true, force: true });
fs.mkdirSync(gen, { recursive: true });
fs.mkdirSync(dist, { recursive: true });

const pascal = (n) => n.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const metadata = {};
const barrel = [];
const symbols = [];
for (const file of fs.readdirSync(srcDir).filter((f) => f.endsWith('.svg')).sort()) {
  const name = file.slice(0, -4);
  const svg = fs.readFileSync(path.join(srcDir, file), 'utf8').trim();
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  const category = svg.match(/data-category="([^"]*)"/)?.[1] ?? 'multi-purpose';
  const keywords = (svg.match(/data-keywords="([^"]*)"/)?.[1] ?? '').split(',').filter(Boolean);
  const component = `${pascal(name)}Icon`;
  metadata[name] = { component, import: `@interlink/icons/core/${name}`, category, keywords };
  fs.writeFileSync(
    path.join(gen, `${name}.ts`),
    `// Generated by scripts/build-icons.mjs. Do not edit.\nimport { createIcon } from '../../icon';\n\nconst ${component} = createIcon(${JSON.stringify(name)}, ${JSON.stringify(inner)});\nexport default ${component};\n`,
  );
  barrel.push(`export { default as ${component} } from './${name}';`);
  symbols.push(`<symbol id="il-icon-${name}" viewBox="0 0 16 16">${inner}</symbol>`);
}
fs.writeFileSync(path.join(gen, 'index.ts'), `// Generated by scripts/build-icons.mjs. Do not edit.\n${barrel.join('\n')}\n`);
fs.writeFileSync(path.join(dist, 'metadata.json'), `${JSON.stringify(metadata, null, 1)}\n`);
fs.writeFileSync(path.join(dist, 'sprite.svg'), `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join('')}</svg>\n`);
fs.copyFileSync(path.join(root, 'src/icon.css'), path.join(dist, 'styles.css'));
console.log(`icons: ${barrel.length} components`);
