// Generates the xcss utility stylesheet and the typed token unions from the token metadata.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { BREAKPOINTS, KIND_PREFIXES, PROPERTIES, PSEUDOS, kebab } from './xcss-spec.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const tokens = JSON.parse(fs.readFileSync(require.resolve('@interlink/tokens/tokens.json'), 'utf8'));
const gen = path.join(root, 'src/generated');
fs.mkdirSync(gen, { recursive: true });

// CSS: one rule per property (base), per pseudo state, and per breakpoint. Values arrive as custom properties.
const rules = [];
const pseudoRules = [];
const mediaRules = Object.fromEntries(Object.keys(BREAKPOINTS).map((b) => [b, []]));
for (const [prop, [, pseudo]] of Object.entries(PROPERTIES)) {
  const p = kebab(prop);
  rules.push(`.il-x-${p} { ${p}: var(--x-${p}); }`);
  if (pseudo) for (const s of PSEUDOS) pseudoRules.push(`.il-x-${s}-${p}:${s} { ${p}: var(--x-${s}-${p}); }`);
  for (const b of Object.keys(BREAKPOINTS)) mediaRules[b].push(`  .il-x-${b}-${p} { ${p}: var(--x-${b}-${p}); }`);
}
const css = [
  '/* SPDX-License-Identifier: Apache-2.0. Generated by scripts/build-xcss.mjs. Do not edit. */',
  '@layer interlink.utilities {',
  ...rules,
  ...pseudoRules,
  ...Object.entries(BREAKPOINTS).map(([b, min]) => `@media (min-width: ${min}) {\n${mediaRules[b].join('\n')}\n}`),
  '}',
].join('\n');
fs.writeFileSync(path.join(gen, 'xcss.css'), `${css}\n`);

// Types: token unions per value kind, and the property -> kind map.
const names = tokens.map((t) => t.name);
const union = (prefixes, negative) =>
  names.filter((n) => prefixes.some((p) => n.startsWith(p)) && (negative || !n.startsWith('space.negative'))).map((n) => `'${n}'`).join(' | ') || 'never';
const ts = [
  '// Generated by scripts/build-xcss.mjs. Do not edit.',
  ...Object.entries(KIND_PREFIXES).map(([k, pre]) => `export type ${k[0].toUpperCase()}${k.slice(1)}Token = ${union(pre, k === 'spaceSigned')};`),
  `export const xcssProperties = ${JSON.stringify(Object.fromEntries(Object.entries(PROPERTIES).map(([p, [k, ps]]) => [p, [k, ps]])))} as const;`,
  `export const breakpoints = ${JSON.stringify(BREAKPOINTS)} as const;`,
  `export const pseudoStates = ${JSON.stringify(PSEUDOS)} as const;`,
].join('\n');
fs.writeFileSync(path.join(gen, 'xcss-types.ts'), `${ts}\n`);
console.log(`xcss: ${Object.keys(PROPERTIES).length} properties, css ${(css.length / 1024).toFixed(1)} KB`);
