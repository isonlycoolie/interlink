// Generates, from examples/:
//   src/generated/registry.ts  guideline Do/Don't components keyed by id, and component example sets
//   src/generated/sources.ts   source text of every example for "Show code", the knowledge base and agent skills
// Each example renders on the client (it may pass icon components into interactive components). A one-line
// 'use client' wrapper per example keeps the registry itself a plain module that servers can read.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const examplesDir = path.join(root, 'examples');
const out = path.join(root, 'src/generated');
const NL = String.fromCharCode(10);
fs.rmSync(path.join(out, 'client'), { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'client'), { recursive: true });

const files = fs.readdirSync(examplesDir, { recursive: true }).map(String).filter((f) => /\.(do|dont|example)\.tsx$/.test(f)).sort();
const imports = [];
const examples = {};
const sets = {};
const sources = {};
const exampleSources = {};
const read = (rel) => fs.readFileSync(path.join(examplesDir, rel), 'utf8').replace(/^\/\/ SPDX-License-Identifier:.*\r?\n/m, '').trim();

files.forEach((rel, i) => {
  const posix = rel.split(path.sep).join('/');
  const [, topic, slug, kind] = posix.match(/^[^/]+\/([^/]+)\/(.+)\.(do|dont|example)\.tsx$/) ?? [];
  if (!topic) return;
  fs.writeFileSync(path.join(out, 'client', `e${i}.tsx`), `'use client';${NL}export { default } from '../../../examples/${posix.replace(/\.tsx$/, '')}';${NL}`);
  imports.push(`import e${i} from './client/e${i}';`);
  const text = read(rel);
  if (kind === 'example') {
    const title = text.match(/\/\*\*\s*Title:\s*([^*\n]+?)\s*\*\//)?.[1] ?? slug.replace(/^\d+-/, '').replace(/-/g, ' ');
    (sets[topic] ||= []).push(`{ slug: ${JSON.stringify(slug)}, title: ${JSON.stringify(title)}, Component: e${i} }`);
    (exampleSources[topic] ||= {})[slug] = text;
    return;
  }
  const id = `${topic}.${slug}`;
  (examples[id] ||= []).push(`${kind}: e${i}`);
  (sources[id] ||= {})[kind] = text;
});

const registry = [
  '// Generated by scripts/build-sources.mjs. Do not edit.',
  "import type { ComponentType } from 'react';",
  ...imports,
  '',
  'export const examples: Record<string, { do?: ComponentType; dont?: ComponentType }> = {',
  ...Object.entries(examples).map(([id, parts]) => `  ${JSON.stringify(id)}: { ${parts.join(', ')} },`),
  '};',
  '',
  'export interface ExampleEntry { slug: string; title: string; Component: ComponentType }',
  'export const exampleSets: Record<string, ExampleEntry[]> = {',
  ...Object.entries(sets).map(([c, list]) => `  ${JSON.stringify(c)}: [${list.join(', ')}],`),
  '};',
];
fs.writeFileSync(path.join(out, 'registry.ts'), registry.join(NL) + NL);

const sourceFile = [
  '// Generated by scripts/build-sources.mjs. Do not edit.',
  `export const sources: Record<string, { do?: string; dont?: string }> = ${JSON.stringify(sources, null, 1)};`,
  `export const exampleSources: Record<string, Record<string, string>> = ${JSON.stringify(exampleSources, null, 1)};`,
];
fs.writeFileSync(path.join(out, 'sources.ts'), sourceFile.join(NL) + NL);
console.log(`guidelines: ${files.length} example files, ${Object.keys(examples).length} guidelines, ${Object.keys(sets).length} example sets`);
