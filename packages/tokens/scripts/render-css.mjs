// Renders resolved token values into the tokens stylesheet.
import { cssVar } from './lib.mjs';

const block = (sel, map, scheme) =>
  `${sel} {\n${scheme ? `  color-scheme: ${scheme};\n` : ''}${Object.entries(map).map(([n, v]) => `  ${cssVar(n)}: ${v};`).join('\n')}\n}`;
const media = (query, body) => `@media ${query} {\n${body}\n}`;
const diff = (base, over) => Object.fromEntries(Object.entries(over).filter(([n, v]) => base[n] !== v));

/**
 * Theme selection:
 * - `data-color-mode` = light | dark on any element (subtree theming works); no attribute follows the OS.
 * - `data-contrast-mode="more"` turns on increased contrast; no attribute follows the OS.
 */
export function renderCss({ themes, root, keyframes }) {
  const { light, dark } = themes;
  const lightMore = diff(light, themes['light-increased-contrast']);
  const darkMore = diff(dark, themes['dark-increased-contrast']);
  return [
    '/* SPDX-License-Identifier: Apache-2.0. Generated by @interlink/tokens. Do not edit. */',
    '@layer interlink.tokens {',
    block(':root, [data-color-mode="light"]', light, 'light'),
    block('[data-color-mode="dark"]', dark, 'dark'),
    media('(prefers-color-scheme: dark)', block(':root:not([data-color-mode])', dark, 'dark')),
    block(':root[data-contrast-mode="more"]:not([data-color-mode="dark"]), [data-color-mode="light"][data-contrast-mode="more"]', lightMore),
    block('[data-color-mode="dark"][data-contrast-mode="more"]', darkMore),
    media('(prefers-contrast: more)', block(':root:not([data-contrast-mode]):not([data-color-mode="dark"])', lightMore)),
    media('(prefers-contrast: more) and (prefers-color-scheme: dark)', block(':root:not([data-contrast-mode]):not([data-color-mode])', themes['dark-increased-contrast'])),
    media('(prefers-contrast: more)', block(':root[data-color-mode="dark"]:not([data-contrast-mode])', darkMore)),
    block(':root', root),
    '}',
    keyframes,
  ].join('\n');
}
