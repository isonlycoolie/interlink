// Builds the token source (src/source) into CSS, JSON and generated TypeScript.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { cssVar, expand, readJson, resolveColor, resolveMotion, toRem } from './lib.mjs';
import { renderCss } from './render-css.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src/source');
const dist = path.join(root, 'dist');
const gen = path.join(root, 'src/generated');
fs.mkdirSync(dist, { recursive: true });
fs.mkdirSync(gen, { recursive: true });

const flat = (obj) => Object.assign({}, ...Object.values(obj));
const colorPalette = flat(readJson(src, 'palette/color.json'));
const shapePalette = readJson(src, 'palette/shape.json');
const spacePalette = readJson(src, 'palette/spacing.json');
const typePalette = readJson(src, 'palette/typography.json');
const motionPalette = readJson(src, 'palette/motion.json');

function loadTheme(name) {
  const dir = path.join(src, 'themes', name);
  const out = {};
  for (const file of fs.readdirSync(dir).sort()) Object.assign(out, expand(readJson(dir, file)));
  return out;
}
const light = loadTheme('light');
const dark = loadTheme('dark');
const themes = {
  light,
  dark,
  'light-increased-contrast': { ...light, ...loadTheme('light-increased-contrast') },
  'dark-increased-contrast': { ...dark, ...loadTheme('dark-increased-contrast') },
};
const resolved = Object.fromEntries(
  Object.entries(themes).map(([t, map]) => [t, Object.fromEntries(Object.entries(map).map(([n, r]) => [n, resolveColor(r, colorPalette, n)]))]),
);

// Non-colour tokens.
const shape = Object.fromEntries(Object.entries(readJson(src, 'shape.json')).map(([n, r]) => [n, toRem(shapePalette[r] ?? r)]));
const spacing = Object.fromEntries(Object.entries(readJson(src, 'spacing.json')).map(([n, r]) => [n, toRem(spacePalette[r] ?? r)]));
const tp = (r) => typePalette[r] ?? r;
const typography = Object.fromEntries(
  Object.entries(readJson(src, 'typography.json')).map(([n, r]) => {
    if (typeof r === 'string') return [n, String(tp(r))];
    const size = toRem(tp(r.fontSize));
    const lh = toRem(tp(r.lineHeight));
    return [n, `${r.fontStyle ?? 'normal'} ${tp(r.fontWeight)} ${size}/${lh} ${tp(r.fontFamily)}`];
  }),
);
const { motion, keyframes } = resolveMotion(expand(readJson(src, 'motion.json')), motionPalette);

// Descriptions.
const descriptions = {};
for (const f of fs.readdirSync(path.join(src, 'descriptions'))) Object.assign(descriptions, readJson(src, `descriptions/${f}`));
const describe = (n) => {
  if (descriptions[n]) return descriptions[n];
  const m = n.match(/^(.*)\.(hovered|pressed)$/);
  return m ? `${m[2][0].toUpperCase()}${m[2].slice(1)} state of ${m[1]}.` : '';
};

// CSS.
const css = renderCss({ themes: resolved, root: { ...shape, ...spacing, ...typography, ...motion }, keyframes });
fs.writeFileSync(path.join(dist, 'tokens.css'), `${css}\n`);

// JSON + generated TS.
const all = { ...resolved.light, ...shape, ...spacing, ...typography, ...motion };
const entries = Object.keys(all).sort().map((n) => ({
  name: n,
  cssVar: cssVar(n),
  description: describe(n),
  group: n.split('.')[0],
  values: n in resolved.light
    ? Object.fromEntries(Object.keys(resolved).map((t) => [t, resolved[t][n]]))
    : { all: all[n] },
}));
fs.writeFileSync(path.join(dist, 'tokens.json'), `${JSON.stringify(entries, null, 1)}\n`);
fs.writeFileSync(path.join(dist, 'palette.json'), `${JSON.stringify(readJson(src, 'palette/color.json'), null, 1)}\n`);
const names = Object.fromEntries(entries.map((e) => [e.name, e.cssVar]));
fs.writeFileSync(
  path.join(gen, 'token-names.ts'),
  `// Generated by scripts/build-tokens.mjs. Do not edit.\nexport const tokenNames = ${JSON.stringify(names, null, 1)} as const;\nexport type TokenName = keyof typeof tokenNames;\n`,
);
console.log(`tokens: ${entries.length} names, css ${(css.length / 1024).toFixed(1)} KB`);
