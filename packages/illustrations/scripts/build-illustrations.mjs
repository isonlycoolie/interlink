// Builds the illustration package from art/*.svg:
//   src/generated/art/<slug>.ts   one component per illustration (palette roles become CSS variables)
//   src/generated/all.ts          every component plus a slug -> component map for galleries
//   dist/styles.css               the palette per theme, read from the token build
//   dist/svg/<slug>.svg           standalone files with the light palette as fallbacks
import fs from 'node:fs';
import path from 'node:path';
import { artDir, checkSvg } from './check-illustrations.mjs';
import { ROLES } from './palette.mjs';

const pkg = path.join(artDir, '..');
const gen = path.join(pkg, 'src', 'generated');
const pascal = (slug) => slug.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const HEADER = '// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/build-illustrations.mjs. Do not edit.\n';

const slugs = fs.readdirSync(artDir).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort();
fs.rmSync(gen, { recursive: true, force: true });
fs.mkdirSync(path.join(gen, 'art'), { recursive: true });
fs.mkdirSync(path.join(pkg, 'dist', 'svg'), { recursive: true });

const failures = [];
for (const slug of slugs) {
  const svg = fs.readFileSync(path.join(artDir, `${slug}.svg`), 'utf8');
  const { problems } = checkSvg(svg);
  if (problems.length) failures.push(`${slug}: ${problems.join('; ')}`);
  const [, w] = /viewBox="0 0 (\d+) (\d+)"/.exec(svg).map(Number);
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '');
  const vars = body.replace(/(fill|stroke)="([PSTQANIW])"/g, (_, attr, k) => `${attr}="var(--il-illo-${ROLES[k].name})"`);
  fs.writeFileSync(
    path.join(gen, 'art', `${slug}.ts`),
    `${HEADER}import { createIllustration } from '../../illustration';\n\nconst ${pascal(slug)} = createIllustration(${JSON.stringify(slug)}, ${JSON.stringify(vars)}, ${w / 96});\nexport default ${pascal(slug)};\n`,
  );
  const standalone = svg.replace(/(fill|stroke)="([PSTQANIW])"/g, (_, attr, k) => `${attr}="var(--il-illo-${ROLES[k].name}, ${ROLES[k].light})"`);
  fs.writeFileSync(path.join(pkg, 'dist', 'svg', `${slug}.svg`), standalone);
}
if (failures.length) throw new Error(`Illustrations failed the quality gate:\n${failures.join('\n')}`);

fs.writeFileSync(
  path.join(gen, 'all.ts'),
  `${HEADER}import type { ComponentType } from 'react';\nimport type { IllustrationProps } from '../illustration';\n` +
    slugs.map((s) => `import ${pascal(s)} from './art/${s}';`).join('\n') +
    `\n\nexport { ${slugs.map(pascal).join(', ')} };\n\n/** Every illustration by slug, for galleries and pickers. */\nexport const illustrations: Record<string, ComponentType<IllustrationProps>> = {\n` +
    slugs.map((s) => `  ${JSON.stringify(s)}: ${pascal(s)},`).join('\n') +
    '\n};\n',
);

const block = (mode) => Object.values(ROLES).map((r) => `  --il-illo-${r.name}: ${r[mode]};`).join('\n');
fs.writeFileSync(
  path.join(pkg, 'dist', 'styles.css'),
  `/* SPDX-License-Identifier: Apache-2.0 */\n/* Generated from the token build by scripts/build-illustrations.mjs. */\n` +
    `@layer interlink.tokens, interlink.reset, interlink.fonts, interlink.base, interlink.components, interlink.utilities;\n@layer interlink.components {\n` +
    `:root, [data-color-mode="light"] {\n${block('light')}\n}\n[data-color-mode="dark"] {\n${block('dark')}\n}\n` +
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-color-mode]) {\n${block('dark')}\n  }\n}\n` +
    `.il-illustration { display: inline-flex; flex-shrink: 0; line-height: 0; vertical-align: middle; }\n` +
    `.il-illustration > svg { display: block; overflow: visible; }\n}\n`,
);
console.log(`illustrations: ${slugs.length} built`);
